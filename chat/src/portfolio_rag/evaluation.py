BASELINE_PATH = settings.resolve_path("data/eval_baseline.json")

# Recorded rewrites, keyed by case id. Written ONLY by
# scripts/refresh_rewrites.py, which is the only thing in this repo that calls
# a real LLM for a rewrite; read here and replayed offline so run_eval.py and
# pytest stay deterministic and network-free. Regenerating is a deliberate,
# reviewed step when the rewrite prompt changes -- the same shape as
# --update-baseline.
REWRITES_PATH = settings.chat_root / "eval" / "rewrites.json"


def load_rewrites(path: Path = REWRITES_PATH) -> dict[str, str]:
    """case id -> recorded standalone question. Empty when the file is absent,
    which scores every multi-turn case as still-refused rather than inventing a
    rewrite -- an absent measurement is never a favourable one."""
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def format_margin(margin: float | None) -> str:
    """Render a gate calibration margin for display.

    None means no artifact on disk records this measurement -- either the
    gate itself isn't available (see Runtime.gate_meta), or it is but was
    built before task 20 added gate_margin. Per this project's established
    rule (the same one that already renders an absent zh gate as "n/a"
    rather than a fabricated pass rate, see scripts/run_eval.py's per-cell
    tables), an absent measurement must render as unavailable -- never as 0,
    0.0%, or any other number that could be mistaken for a real, and
    misleadingly healthy, margin.
    """
    return "n/a" if margin is None else f"{margin:+.1%}"


def build_baseline(rt: Runtime, cells: dict) -> dict:
    """The frozen snapshot `scripts/run_eval.py --update-baseline` writes to
    BASELINE_PATH, and tests/test_golden.py's test_no_metric_regressed reads
    back. Lives here rather than in the CLI script for the same reason
    BASELINE_PATH itself does: so the CLI and a future test share one
    definition instead of two that can silently drift apart.

    rt.gate_meta's margin (see Runtime.gate_meta / _GateBundle) rides
    straight through into gate.<lang>.margin as either a float or None (JSON
    null) -- deliberately NOT run through format_margin, which is a display
    concern for the printed table, not for what gets persisted to disk.
    test_no_metric_regressed intentionally does not compare this field: it
    is a reported diagnostic (how the margin is decaying build over build),
    not a pass/fail metric, and _find_regressions's cells-only comparison
    never sees the top-level "gate" key at all.
    """
    return {
        "k": TOP_K,
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "index_built_at": rt.index_built_at,
        "gate": rt.gate_meta,
        "cells": cells,
    }


@dataclass(frozen=True)
class GoldenCase:
    id: str
    role: str
    lang: str
    type: str
    q: str
    expected_urls: tuple[str, ...] = ()
    # 1-4 proper nouns / technical terms that must appear in the retrieved text.
    # Page-level expected_urls says "right page"; these say "right passage".
    expected_keywords: tuple[str, ...] = ()
    note: str = ""
    # Required on off_topic ("easy" or "adjacent"); empty on positive and
    # injection. See ADJACENCY, and load_cases, which enforces it.
    adjacency: str = ""
    # Prior conversation turns, as (role, content) pairs -- pairs rather than
    # dicts because this dataclass is frozen and therefore hashable, which a
    # dict field would break. Empty for the single-turn cases that make up most
    # of the set. A case WITH history exercises the escalated follow-up path:
    # the question is judged in isolation first, and only if that fails does the
    # recorded rewrite come into play (see score_case).
    history: tuple[tuple[str, str], ...] = ()

    @property
    def messages(self) -> list[dict]:
        """The history in the {role, content} shape the rewrite call takes."""
        return [{"role": r, "content": c} for r, c in self.history]

    @property
    def cell(self) -> str:
        """positive cells are per (role, lang); negatives share one pool per
        language (SHARED_ROLE) because they no longer belong to any role."""
        if self.type == "positive":
            return f"{self.role}/{self.lang}"
        return f"{SHARED_ROLE}/{self.lang}"


def load_cases(path: Path = GOLDEN_PATH) -> list[GoldenCase]:
    """Load and VALIDATE the golden set.

    `adjacency` used to be read without validation, plus a matching tolerance
    in aggregate() (a dynamic "unmigrated" bucket) and two more pieces in
    scripts/run_eval.py that found those buckets again and footnoted them --
    ~25 lines coordinated across three files so the CLI kept working over a
    dataset not yet migrated to the adjacency schema. That migration is
    complete (all 16 off_topic cases carry a valid easy/adjacent; all 96
    positives and 8 injections correctly carry none) and
    tests/test_golden.py::test_off_topic_adjacency_is_valid forbids the
    untolerated state from returning. Tolerating a condition that cannot
    occur, and that is separately asserted not to, is machinery with nothing
    to do -- so the tolerance is gone and this is now the single place the
    schema is enforced."""
    cases: list[GoldenCase] = []
    for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        try:
            raw = json.loads(line)
        except json.JSONDecodeError as err:
            raise ValueError(f"{path.name}:{lineno}: invalid JSON — {err}") from err
        missing = {"id", "role", "lang", "type", "q"} - set(raw)
        if missing:
            raise ValueError(f"{path.name}:{lineno}: missing field(s) {sorted(missing)}")
        adjacency = raw.get("adjacency", "")
        if raw["type"] == "off_topic" and adjacency not in ADJACENCY:
            raise ValueError(
                f"{path.name}:{lineno}: off_topic case {raw['id']!r} has adjacency "
                f"{adjacency!r}, not one of {ADJACENCY}. It drives the shared-negative "
                "bucketing, and a case that lands in no bucket is a case nothing measures."
            )
        if raw["type"] != "off_topic" and adjacency:
            raise ValueError(
                f"{path.name}:{lineno}: {raw['type']} case {raw['id']!r} must not carry "
                f"adjacency (has {adjacency!r}) -- injections are adjacent by definition "
                "and positives have no adjacency at all."
            )
        raw_history = raw.get("history", [])
        if not isinstance(raw_history, list):
            raise ValueError(f"{path.name}:{lineno}: case {raw['id']!r} has a non-list history")
        history = []
        for turn in raw_history:
            if not isinstance(turn, dict) or turn.get("role") not in ("user", "assistant"):
                raise ValueError(
                    f"{path.name}:{lineno}: case {raw['id']!r} has a history turn with role "
                    f"{turn.get('role') if isinstance(turn, dict) else turn!r}, not 'user' or "
                    "'assistant'"
                )
            if not isinstance(turn.get("content"), str):
                raise ValueError(
                    f"{path.name}:{lineno}: case {raw['id']!r} has a history turn with "
                    "non-string content"
                )
            history.append((turn["role"], turn["content"]))
        if history:
            roles = [r for r, _ in history]
            if roles != ["user" if i % 2 == 0 else "assistant" for i in range(len(roles))]:
                raise ValueError(
                    f"{path.name}:{lineno}: case {raw['id']!r} has a history that does not "
                    "alternate user/assistant starting with user -- the widget only ever "
                    "appends in pairs, so this is not a conversation it could have produced"
                )
            if roles[-1] != "assistant":
                raise ValueError(
                    f"{path.name}:{lineno}: case {raw['id']!r} has a history ending on a user "
                    "turn -- it must end on the assistant turn the follow-up follows"
                )
        cases.append(
            GoldenCase(
                id=raw["id"],
                role=raw["role"],
                lang=raw["lang"],
                type=raw["type"],
                q=raw["q"],
                expected_urls=tuple(raw.get("expected_urls", ())),
                expected_keywords=tuple(raw.get("expected_keywords", ())),
                note=raw.get("note", ""),
                adjacency=adjacency,
                history=tuple(history),
            )
        )
    return cases


# ASCII-only word characters, deliberately NOT \w. Python's \w is
# Unicode-aware and treats CJK as word characters, so r"(?<!\w)Hive" would
# refuse to match inside "在Hive关卡中" — every Latin keyword in a Chinese
# chunk would read as missing. JavaScript's \w is ASCII-only, which is the
# semantics we actually want here. (runtime.NAME_RE carries the same fix.)
_WORD_CHAR = "a-zA-Z0-9_"


def _keyword_pattern(keyword: str) -> re.Pattern:
    """Word boundaries only where the keyword's own edge is ASCII alphanumeric.

    'AI' gets both boundaries, so it cannot match inside 'available'. 'C++'
    gets a leading boundary only, because '+' is not a word character and a
    trailing boundary would never fire after it. CJK keywords get neither —
    Chinese has no word separators, so a plain substring match is correct.
    """
    left = f"(?<![{_WORD_CHAR}])" if keyword[:1].isascii() and keyword[:1].isalnum() else ""
    right = f"(?![{_WORD_CHAR}])" if keyword[-1:].isascii() and keyword[-1:].isalnum() else ""
    return re.compile(left + re.escape(keyword) + right, re.I)


def keyword_matches(text: str, keywords) -> tuple[tuple[str, ...], tuple[str, ...]]:
    """Split keywords into (found, missing) against one blob of retrieved text."""
    found, missing = [], []
    for kw in keywords:
        (found if _keyword_pattern(kw).search(text) else missing).append(kw)
    return tuple(found), tuple(missing)


@dataclass(frozen=True)
class CaseResult:
    case: GoldenCase
    gate_passed: bool
    gate_value: float | None
    gate_available: bool
    hit: bool | None
    top_urls: tuple[str, ...]
    top_scores: tuple[float, ...]
    keywords_found: tuple[str, ...] = ()
    keywords_missing: tuple[str, ...] = ()
    retrieved_langs: dict[str, int] = field(default_factory=dict)
    dropped_by_floor: int = 0
    # Task 24 review, Critical 1: hit computed with the curated
    # chat/knowledge/about_<lang>.md sections excluded from the candidate
    # pool -- "would the site's OWN pages have surfaced this, with no
    # curated-corpus assist." A diagnostic, not a second pass/fail metric:
    # see aggregate()'s hit_at_4_page_only and _find_regressions in
    # tests/test_golden.py, which deliberately does not compare it.
    hit_page_only: bool | None = None
    # The AUTHORITATIVE reason Runtime.gate() reached its verdict
    # (GateDecision.reason: "cjk_bypass", "no_en_gate", or None for a real
    # measurement). Carried through rather than re-derived downstream:
    # aggregate() used to infer "this was a CJK bypass" from
    # `gate_value is None and case.lang == "zh"`, which is a proxy that
    # coincides with the truth only while every case's declared language
    # matches the language its GATE TEXT routes to -- nothing enforces that
    # and nothing tested it. An en-lang case whose question carries CJK
    # routes to the zh gate; on a machine with no gate_zh_bge.json (it is
    # gitignored, so every fresh clone) it bypassed, and the proxy then
    # reported gate_available=True and scored the bypass as a refusal
    # FAILURE -- a missing measurement recorded as a zero, which this
    # project's working agreements forbid. This is the fifth proxy-signal
    # defect on the branch; the fix is to thread the real value, not to pick
    # a better stand-in.
    gate_reason: str | None = None
    # The recorded rewrite that was actually replayed, or None when this case
    # had no history, cleared the gate on its own, or had no fixture entry.
    rewrite_used: str | None = None
    # Positives with a REPLAYED rewrite only (rewrite_used is not None): did
    # the rewrite turn a gate refusal into a pass AND land the expected page?
    # None whenever no rewrite was actually replayed -- no history, the raw
    # question already passed the gate, or the fixture had no entry -- so a
    # follow-up that was never broken can never register as a rescue.
    rescued: bool | None = None

    @property
    def ok(self) -> bool:
        """Did this case behave as the dataset says it should?"""
        if self.case.type == "positive":
            return self.gate_passed and bool(self.hit) and not self.keywords_missing
        return not self.gate_passed


def score_case(rt: Runtime, case: GoldenCase, rewrites: dict[str, str] | None = None) -> CaseResult:
    # Retrieval runs for every case type, and hit/keywords are computed WITHOUT
    # consulting the gate: a gate failure must never mask retrieval quality.
    retrieval = rt.retrieve(case.q, k=TOP_K)
    decision = rt.gate(case.q)
    rewrite_used = None
    rescued = None
    # The escalated path, replayed: the raw question is judged first, and only a
    # REFUSAL with a conversation behind it consults the fixture. This mirrors
    # the runtime's laziness exactly -- a follow-up that stands on its own never
    # reaches the rewriter in production either.
    if case.history and not decision.passed:
        rewrite = (rewrites or {}).get(case.id)
        if rewrite:
            rewrite_used = rewrite
            decision = rt.gate(rewrite)
            retrieval = rt.retrieve(rewrite, k=TOP_K)
    urls = tuple(h.url for h in retrieval.hits)
    hit = None
    hit_page_only = None
    found: tuple[str, ...] = ()
    missing: tuple[str, ...] = ()
    if case.type == "positive":
        hit = bool(set(urls) & set(case.expected_urls))
        # Page-only diagnostic (task 24 review, Critical 1): re-rank with the
        # curated knowledge/about_<lang>.md sections excluded from the
        # candidate pool BEFORE top-k is taken (see Runtime.retrieve's
        # exclude_ids), not a post-hoc filter of the already-computed `hits`
        # above -- a page chunk ranked 5th overall but 4th once the curated
        # corpus is out of the running still deserves credit here. Ranks
        # whatever was actually queried (the rewrite when one was replayed,
        # case.q otherwise) so this diagnostic never silently measures a
        # different query than the main path did.
        page_retrieval = rt.retrieve(rewrite_used or case.q, k=TOP_K, exclude_ids=rt.knowledge_chunk_ids)
        hit_page_only = bool(set(h.url for h in page_retrieval.hits) & set(case.expected_urls))
        # Matched against the concatenated post-floor top-4 — exactly the text
        # that becomes `contexts`. This is "was the fact available to the model?"
        blob = " ".join(rt.chunk_text(h.chunk_id) for h in retrieval.hits)
        found, missing = keyword_matches(blob, case.expected_keywords)
        # Gated on rewrite_used, NOT bare case.history: a follow-up that
        # cleared the gate on its own never consulted the fixture (see above),
        # so there was no rewrite for it to be "rescued" by -- scoring it here
        # would inflate the rescue-rate metric with cases that were never
        # broken. rescued only answers "did a REPLAYED rewrite turn a refusal
        # into a pass," which requires a rewrite to have actually run.
        if rewrite_used is not None:
            rescued = bool(decision.passed and hit)
    return CaseResult(
        case=case,
        gate_passed=decision.passed,
        gate_value=decision.value,
        gate_available=decision.available,
        gate_reason=decision.reason,
        hit=hit,
        top_urls=urls,
        top_scores=tuple(h.score for h in retrieval.hits),
        keywords_found=found,
        keywords_missing=missing,
        retrieved_langs=dict(Counter(h.lang for h in retrieval.hits)),
        dropped_by_floor=retrieval.dropped_by_floor,
        hit_page_only=hit_page_only,
        rewrite_used=rewrite_used,
        rescued=rescued,
    )


def run_cases(rt: Runtime, cases: list[GoldenCase], rewrites: dict[str, str] | None = None) -> list[CaseResult]:
    return [score_case(rt, c, rewrites) for c in cases]


def aggregate(results: list[CaseResult]) -> dict[str, dict]:
    """Positive cells (`role/lang`) and shared negative cells (`shared/lang`)
    are shaped differently and never blended into each other: a positive
    cell reports gate-pass and retrieval health (plus, for the multi-turn
    subset, follow-up rescue -- n_followup/followup_rescued); a shared cell
    reports refusal broken out by bucket (off_topic/easy, off_topic/adjacent,
    injection, post_context), because "the gate is broken," "the gate cannot
    separate the domain from what's merely adjacent to it," and "the rewrite
    is smuggling conversational context into a question that should still be
    refused" demand three different fixes and a blended number cannot tell
    you which one you have.
    """
    cells: dict[str, dict] = {}
    for r in results:
        c = r.case
        if c.type == "positive":
            cell = cells.setdefault(
                c.cell,
                {
                    "role": c.role, "lang": c.lang,
                    "n_positive": 0, "n_negative": 0,
                    "gate_pass": 0, "hit_at_4": 0,
                    # Diagnostic, not a pass/fail metric -- deliberately absent
                    # from tests/test_golden.py's _REGRESSION_METRICS. See
                    # CaseResult.hit_page_only and Runtime.knowledge_chunk_ids.
                    "hit_at_4_page_only": 0,
                    "keywords_found": 0, "keywords_total": 0,
                    "gate_available": True,
                    "retrieved_langs": {},
                    # Multi-turn positives only. Reported separately from
                    # gate_pass because "the gate refuses this question in
                    # isolation" is the EXPECTED state for these cases -- the
                    # measurement is whether the rewrite recovers it.
                    "n_followup": 0, "followup_rescued": 0,
                },
            )
            # Multi-turn positives count ONLY toward n_followup/followup_rescued,
            # never toward n_positive/gate_pass/hit_at_4/hit_at_4_page_only/
            # keywords_found/keywords_total/retrieved_langs. Folding them into
            # those single-turn metrics would grow a cell's DENOMINATOR every
            # time a follow-up case is added, silently dragging down hit@4 and
            # keyword coverage for cells that were never meant to be affected --
            # exactly the contamination task 9's own review caught (two existing
            # cells' keyword coverage moved after the four new follow-up
            # positives landed, with no change to either cell's single-turn
            # cases). A follow-up's retrieval quality is already captured by
            # `rescued`, which requires landing the expected page -- see
            # CaseResult.rescued's docstring -- so nothing is lost by excluding
            # it here, only double-counted.
            #
            # gate_available (below, past this if/else) is the deliberate
            # EIGHTH exception to "excluded here": it is set unconditionally
            # from every CaseResult, multi-turn included. That is correct, not
            # an oversight -- gate_available describes whether THE GATE itself
            # produced a real measurement (vs. a cjk_bypass decision) for
            # whatever text it was asked to judge, which is a property of the
            # gate call a follow-up case makes exactly like a single-turn one
            # does, not a property of the case's own retrieval/rescue outcome
            # the way n_positive/hit_at_4/keywords_* are. Excluding it here
            # too would silently hide a cjk_bypass a follow-up's re-gate hit.
            if c.history:
                cell["n_followup"] += 1
                cell["followup_rescued"] += int(bool(r.rescued))
            else:
                cell["n_positive"] += 1
                cell["gate_pass"] += int(r.gate_passed)
                cell["hit_at_4"] += int(bool(r.hit))
                cell["hit_at_4_page_only"] += int(bool(r.hit_page_only))
                # Coverage, not all-or-nothing: 1/4 and 3/4 must stay distinguishable.
                cell["keywords_found"] += len(r.keywords_found)
                cell["keywords_total"] += len(r.keywords_found) + len(r.keywords_missing)
                for lang, n in r.retrieved_langs.items():
                    cell["retrieved_langs"][lang] = cell["retrieved_langs"].get(lang, 0) + n
        else:
            cell = cells.setdefault(
                c.cell,
                {
                    "role": SHARED_ROLE, "lang": c.lang,
                    "n_positive": 0, "n_negative": 0,
                    "refusal_easy": 0, "n_easy": 0,
                    "refusal_adjacent": 0, "n_adjacent": 0,
                    "refusal_injection": 0, "n_injection": 0,
                    "refusal_post_context": 0, "n_post_context": 0,
                    "gate_available": True,
                },
            )
            cell["n_negative"] += 1
            # Bucketed by whether a conversation precedes the question, ahead of
            # adjacency: adjacency measures how close the QUESTION is to the
            # domain, which is orthogonal to whether the CONVERSATION can lend
            # it topicality. A post-context negative that regressed would
            # otherwise be averaged into the easy/adjacent numbers and vanish.
            if c.type == "injection":
                bucket = "injection"
            elif c.history:
                bucket = "post_context"
            else:
                bucket = c.adjacency
            cell[f"refusal_{bucket}"] += int(not r.gate_passed)
            cell[f"n_{bucket}"] += 1
        # A cjk_bypass decision means there is no zh gate; the gate columns for
        # that cell are unmeasured rather than perfect. Read off the decision's
        # OWN reason (threaded through CaseResult.gate_reason -- see its
        # comment), never re-derived from the case's declared language: those
        # two agree only while no case's gate text routes to a language other
        # than the one the case declares, which nothing enforces.
        if not r.gate_available or r.gate_reason == "cjk_bypass":
            cell["gate_available"] = False
    return cells
